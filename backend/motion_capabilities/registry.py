class MotionCapabilitiesRegistry:
    """Singleton query interface for all Motion capabilities."""

    @classmethod
    def list_all(cls) -> List[MotionCapabilitySpec]:
        return list(ALL_CAPABILITIES_SPEC)

    CAPABILITY_ALIASES: Dict[str, str] = {
        "extract-audio": "remove-audio",
        "enhance-audio": "audio-enhance",
        "silence-remover": "remove-silence",
        "split-silence": "remove-silence",
        "timeline-clip-split": "split-at-playhead",
        "timeline-slip-edit": "slip-editing",
        "timeline-ripple-delete": "ripple-delete",
        "timeline-retime-playback": "speed",
        "b-roll-lane-placement": "source-video-library",
        "audio-framing-parity": "reframe",
        "multiline-caption-override": "manual-caption-override",
        "source-bench-ranges": "filmstrip-range-bench",
        "metadata": "video-download",
    }

    @classmethod
    def get(cls, capability_id: str) -> Optional[MotionCapabilitySpec]:
        target_id = cls.CAPABILITY_ALIASES.get(capability_id, capability_id)
        for cap in ALL_CAPABILITIES_SPEC:
            if cap.id == target_id:
                return cap
        return None

    @classmethod
    def filter_by_category(cls, category: CapabilityCategory) -> List[MotionCapabilitySpec]:
        return [c for c in ALL_CAPABILITIES_SPEC if c.category == category]

    @classmethod
    def filter_by_tier(cls, tier: ParityTier) -> List[MotionCapabilitySpec]:
        return [c for c in ALL_CAPABILITIES_SPEC if c.parity_tier == tier]

    @classmethod
    def count(cls) -> int:
        return len(ALL_CAPABILITIES_SPEC)
