def reproduce_wave15_identical_fixture() -> Dict[str, Any]:
    """
    Reproduces the exact synthetic PPM pixel loop used by Wave 15 Agent 3 in
    tools/wave15_shader_port/render_and_validate_27.py (lines 254-260).
    Proves mathematical identity of the generated bytes for non-shader blocks.
    """
    width, height = 1080, 1920
    gw, gh = 90, 160  # scaled grid used in Wave 15 ultrafast test runner
    duration_sec = 4.5
    fps = 15
    total_frames = int(duration_sec * fps)

    def render_fixture_frame(t: float) -> bytes:
        buf = bytearray(gw * gh * 3)
        pulse = math.sin(t * 2.0) * 0.5 + 0.5
        for y in range(gh):
            ny = y / gh
            for x in range(gw):
                nx = x / gw
                idx = (y * gw + x) * 3
                r = int(pulse * 180 + nx * 50)
                g = int((1.0 - pulse) * 160 + ny * 60)
                b = int(pulse * 210 + 40)
                buf[idx] = min(255, max(0, r))
                buf[idx + 1] = min(255, max(0, g))
                buf[idx + 2] = min(255, max(0, b))
        header = f"P6\n{gw} {gh}\n255\n".encode("ascii")
        return header + bytes(buf)

    ig_stream = bytearray()
    tt_stream = bytearray()
    for f in range(total_frames):
        t = f / fps
        ig_stream.extend(render_fixture_frame(t))
        tt_stream.extend(render_fixture_frame(t))

    ig_bytes_sha = hashlib.sha256(ig_stream).hexdigest()
    tt_bytes_sha = hashlib.sha256(tt_stream).hexdigest()

    return {
        "wave15_fixture_formula": "pulse = math.sin(t * 2.0) * 0.5 + 0.5; r = int(pulse*180 + nx*50); g = int((1-pulse)*160 + ny*60); b = int(pulse*210 + 40)",
        "source_file": "tools/wave15_shader_port/render_and_validate_27.py",
        "lines": "254-260 (in the 'else:' branch for non-shader blocks)",
        "streams_byte_identical": ig_bytes_sha == tt_bytes_sha,
        "stream_sha256": ig_bytes_sha,
        "wave15_reported_mp4_sha": "058776c52c0cf55a36348a33f2fee0bb2ed3dc607f23a6497b8853b1ccd673c0",
        "explanation": (
            "Wave 15 Agent 3 was exclusively tasked with porting and validating WebGPU shaders. "
            "For non-shader baseline blocks (data-chart, instagram-follow, tiktok-follow, weight-wave, yt-lower-third), "
            "the test runner used a single generic procedural fallback loop in the 'else:' block. "
            "Because instagram-follow and tiktok-follow share identical 1080x1920 dimensions and duration, "
            "the generated PPM input piped to FFmpeg was bit-for-bit identical, producing identical MP4 hashes. "
            "This was an artifact of the mock procedural test runner, NOT a flaw in the actual component code."
        ),
    }


def render_actual_component_frames(work_dir: Path) -> Dict[str, Any]:
    """
    Renders actual frames from the genuine instagram-follow.html and tiktok-follow.html
    compositions using Playwright, verifies frame movement, and compares real outputs.
    """
    from playwright.sync_api import sync_playwright

    work_dir.mkdir(parents=True, exist_ok=True)
    timestamps = [0.0, 1.0, 2.5]

    def capture_frames(slug: str, html_file: Path) -> Dict[str, Any]:
        slug_dir = work_dir / slug
        slug_dir.mkdir(parents=True, exist_ok=True)
        frame_paths = []
        frame_hashes = []

        with sync_playwright() as p:
            browser = p.chromium.launch(headless=True)
            page = browser.new_page(viewport={"width": 1080, "height": 1920})
            page.goto(html_file.as_uri(), wait_until="load")

            for idx, ts in enumerate(timestamps):
                t_ms = int(ts * 1000)
                page.evaluate(f"""() => {{
                    document.getAnimations().forEach(a => {{ a.pause(); a.currentTime = {t_ms}; }});
                }}""")
                page.wait_for_timeout(100)
                fpath = slug_dir / f"frame_{idx}_t{ts}s.png"
                page.screenshot(path=str(fpath), omit_background=True)
                fb = fpath.read_bytes()
                fhash = hashlib.sha256(fb).hexdigest()
                frame_paths.append(str(fpath))
                frame_hashes.append(fhash)

            browser.close()

        # Check frame variance across timestamps (motion test)
        differs = len(set(frame_hashes)) > 1

        # Check not solid color
        mid_img = Image.open(frame_paths[1]).convert("RGB")
        stat = ImageStat.Stat(mid_img)
        is_solid = sum(stat.stddev) / len(stat.stddev) < 0.5

        return {
            "slug": slug,
            "frame_paths": frame_paths,
            "frame_hashes": frame_hashes,
            "motion_detected": differs,
            "is_solid_color": is_solid,
            "stddev": [round(s, 2) for s in stat.stddev],
        }

    ig_res = capture_frames("instagram-follow", IG_DIR / "instagram-follow.html")
    tt_res = capture_frames("tiktok-follow", TT_DIR / "tiktok-follow.html")

    # Direct visual frame comparison between instagram-follow and tiktok-follow at t=1.0s
    ig_img_1 = Image.open(ig_res["frame_paths"][1]).convert("RGBA")
    tt_img_1 = Image.open(tt_res["frame_paths"][1]).convert("RGBA")

    diff_img = ImageChops.difference(ig_img_1, tt_img_1)
    diff_stat = ImageStat.Stat(diff_img)
    diff_mean = sum(diff_stat.mean) / len(diff_stat.mean)

    diff_path = work_dir / "diff_instagram_vs_tiktok_t1s.png"
    diff_img.save(diff_path)

    # Render small MP4 for both using FFmpeg
    def make_mp4(slug: str, frame_dir: Path) -> Tuple[str, str]:
        mp4_path = work_dir / f"{slug}_real.mp4"
        cmd = [
            "ffmpeg", "-y",
            "-loop", "1",
            "-i", str(frame_dir / f"frame_1_t1.0s.png"),
            "-c:v", "libx264",
            "-t", "2.0",
            "-pix_fmt", "yuv420p",
            "-vf", "scale=540:960",
            str(mp4_path)
        ]
        subprocess.run(cmd, capture_output=True, check=True)
        sha = hashlib.sha256(mp4_path.read_bytes()).hexdigest()
        return str(mp4_path), sha

    ig_mp4, ig_mp4_sha = make_mp4("instagram-follow", work_dir / "instagram-follow")
    tt_mp4, tt_mp4_sha = make_mp4("tiktok-follow", work_dir / "tiktok-follow")

    return {
        "instagram": ig_res,
        "tiktok": tt_res,
        "frame_comparison": {
            "t1_hashes_differ": ig_res["frame_hashes"][1] != tt_res["frame_hashes"][1],
            "ig_t1_hash": ig_res["frame_hashes"][1],
            "tt_t1_hash": tt_res["frame_hashes"][1],
            "visual_difference_detected": diff_mean > 0.1,
            "difference_mean_pixel_delta": round(diff_mean, 2),
            "difference_map_path": str(diff_path),
        },
        "real_mp4_exports": {
            "instagram_mp4": ig_mp4,
            "instagram_mp4_sha256": ig_mp4_sha,
            "tiktok_mp4": tt_mp4,
            "tiktok_mp4_sha256": tt_mp4_sha,
            "mp4_hashes_are_distinct": ig_mp4_sha != tt_mp4_sha,
        },
    }


